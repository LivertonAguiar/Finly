export const t = (key: string, lang: SupportedLanguage = 'pt-BR', defaultText?: string): string => {
  return DICTIONARY[lang]?.[key] || DICTIONARY['pt-BR']?.[key] || defaultText || key;
};

export const translateCategoryName = (categoryName: string, lang: SupportedLanguage = 'pt-BR'): string => {
  if (lang === 'pt-BR' || !categoryName) return categoryName;
  const match = CATEGORY_TRANSLATIONS[categoryName];
  if (match) {
    return lang === 'en-US' ? match.en : match.es;
  }
  return categoryName;
};

export const useTranslation = () => {
  const { user } = useFinancial();
  const lang = (user?.language as SupportedLanguage) || 'pt-BR';

  return {
    lang,
    t: (key: string, defaultText?: string) => t(key, lang, defaultText),
    translateCategory: (name: string) => translateCategoryName(name, lang),
  };
};
